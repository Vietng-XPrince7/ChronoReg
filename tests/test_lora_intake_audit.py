"""Safety gate tests independent of Torch or Hugging Face."""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from src.lora.intake_audit import classify_qa, ensure_curated, audit


def test_autogenerated_approval_is_not_human_review():
    row = {'id': 'x1', 'reviewer': 'Antigravity QA Reviewer', 'answer': 'A valid figure'}
    assert 'AUTOMATED_REVIEWER' in classify_qa(row)
    with pytest.raises(ValueError, match='non-human review'):
        ensure_curated([row])


def test_template_nonanswer_blocked_even_with_other_reviewer():
    row = {'id': 'x2', 'reviewer': 'Sample Reviewer', 'answer': (
        'Căn cứ theo văn bản quy định của Trường Đại học Công nghệ áp dụng trong năm học 2022-2023, '
        'nội dung được quy định như sau: Trường Đại học Công nghệ.')}
    assert 'TEMPLATE_NONANSWER' in classify_qa(row)
    with pytest.raises(ValueError, match='template non-answers'):
        ensure_curated([row])


def test_detailed_answer_not_blanket_rejected():
    row = {'id': 'x3', 'reviewer': 'Human Reviewer', 'answer': 'Hạn cuối là ngày 15/02/2023.'}
    ensure_curated([row])
    assert not classify_qa(row)


def test_generic_question_is_diagnostic_only():
    row = {'id': 'x4', 'reviewer': 'Human Reviewer',
           'question': 'Theo văn bản, nội dung về học phí được quy định cụ thể như thế nào?',
           'answer': 'Mức thu là 2.000.000 đồng/tháng.'}
    assert 'GENERIC_QUESTION' in classify_qa(row)
    ensure_curated([row])


def test_audit_reports_stale_manifest_and_provenance(tmp_path):
    repo = tmp_path
    docs = repo / 'data/raw/uet/markdown/2022'
    docs.mkdir(parents=True)
    source = docs / 'a.md'
    source.write_text('Source quote 2022', encoding='utf-8')
    import hashlib
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    train = repo / 'train.jsonl'
    train.write_text(json.dumps({'id': 'x1', 'reviewer': 'Antigravity QA Reviewer',
                                 'answer': 'Value', 'question': 'What?',
                                 'source_file': str(source.relative_to(repo)),
                                 'source_sha256': digest, 'evidence_quote': 'Source quote',
                                 'as_of_year': 2022})+'\n', encoding='utf-8')
    benchmark = repo / 'data/qa_benchmark/benchmark.jsonl'
    benchmark.parent.mkdir(parents=True)
    benchmark.write_text(json.dumps({'id': 'b1', 'type': 'active_rule', 'question': 'Different?',
                                     'source_sha256': digest, 'as_of_year': 2022})+'\n')
    (benchmark.parent / 'valid.jsonl').write_text(benchmark.read_text())
    (benchmark.parent / 'superseded.jsonl').write_text('')
    (benchmark.parent / 'year_specific.jsonl').write_text('')
    prepared = repo / 'prepared'
    prepared.mkdir()
    (prepared / 'manifest.json').write_text(json.dumps({'train_sha256': 'stale',
                              'benchmark_sha256': 'stale', 'year_sha256': {}, 'counts': {}}))
    result, cases = audit(repo, train, benchmark, prepared)
    assert result['status'] == 'BLOCKED_FOR_TRAINING'
    assert result['train']['blocking_rows'] == 1
    assert result['prepared_manifest']['train_source_sha_matches'] is False
    assert result['prepared_manifest']['benchmark_sha_matches'] is False
    assert result['benchmark']['missing_source_ids'] == []
    assert cases[0]['flags'] == ['AUTOMATED_REVIEWER']


def test_real_handoff_detected_without_rewriting_data():
    repo = Path(__file__).resolve().parents[1]
    train = repo / 'src/lora/runs/approved_qa.jsonl'
    bench = repo / 'data/qa_benchmark/benchmark.jsonl'
    if not (train.is_file() and bench.is_file()):
        pytest.skip('Handoff artifacts not available in this checkout')
    report, _ = audit(repo, train, bench, repo / 'src/lora/runs/prepared')
    assert report['status'] == 'BLOCKED_FOR_TRAINING'
    assert report['train']['count'] == 200
    assert report['train']['blocking_rows'] == 200
    assert report['benchmark']['count'] == 90
    assert report['benchmark']['structural_errors'] == []
